import AppKit
import NaviCore

@MainActor
final class ClipboardWatcher {
    static let skippedTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
        NaviPasteboard.ownType,
    ]

    private let inbox: Inbox
    private let pasteboard: NSPasteboard
    private var lastChangeCount: Int
    private var ownChangeCount: Int?
    private var timer: Timer?

    init(inbox: Inbox, pasteboard: NSPasteboard = .general) {
        self.inbox = inbox
        self.pasteboard = pasteboard
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func markOwnChange(_ changeCount: Int) {
        ownChangeCount = changeCount
    }

    func check() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount
        guard changeCount != ownChangeCount else { return }

        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.skippedTypes) else { return }

        let app = NSWorkspace.shared.frontmostApplication
        let sourceApp = app?.localizedName
        let bundleID = app?.bundleIdentifier
        if let text = pasteboard.string(forType: .string) {
            inbox.add(text: text, sourceApp: sourceApp, sourceBundleID: bundleID)
        } else if let png = Self.pngData(from: pasteboard) {
            inbox.add(fileData: png, fileExtension: "png", kind: .image, sourceApp: sourceApp, sourceBundleID: bundleID)
        }
    }

    private static func pngData(from pasteboard: NSPasteboard) -> Data? {
        if let png = pasteboard.data(forType: .png) { return png }
        guard let tiff = pasteboard.data(forType: .tiff), let bitmap = NSBitmapImageRep(data: tiff) else { return nil }
        return bitmap.representation(using: .png, properties: [:])
    }
}
